// Draws this site's painted strokes and ink marks into site-src/kit/brushes.css, from the colours in
// site-src/kit/identity.css (so no colour is written down twice). The drawing itself is the shared tool
// tools/kit-brush.cjs, the same file as on divergenttherapy.org, used here through what it exports.
//   node tools/fs-brushes.cjs          writes site-src/kit/brushes.css (run it after changing a colour in identity.css)
//   node tools/fs-brushes.cjs --check  exits 1 if brushes.css is not what identity.css would draw (the build runs this)
const fs = require('fs');
const path = require('path');
const K = require('./kit-brush.cjs');
const KIT = path.join(__dirname, '..', 'site-src', 'kit');

function slots(css) {
  const out = {};
  for (const m of css.matchAll(/(--[\w-]+):\s*([^;]+);/g)) if (!(m[1] in out)) out[m[1]] = m[2].trim();
  return out;
}
function draw(identity) {
  const s = slots(identity), need = k => { if (!s[k]) throw new Error(`identity.css has no ${k}`); return s[k]; };
  const paint = k => need(k).split(',').map(c => c.trim());
  const rgba = v => { const m = v.match(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/); return ['#' + [m[1], m[2], m[3]].map(n => (+n).toString(16).padStart(2, '0')).join(''), +m[4]]; };
  const lines = [];
  // the buttons are stamped prints (identity.css, --brush-*), not drawn here
  // keyboard focus: one brush-pen stroke, the ink on every ground 
  lines.push(`--focus-ink: ${K.stroke(7, need('--c-focus'))};`);
  lines.push(`--focus-ink-deep: ${K.stroke(7, need('--c-focus-deep'))};`);
  // the hand-drawn lines: the upright accent line, the line under a field, the link underline (rest, pointer, footer)
  lines.push(`--rule-ink-v: ${K.upright(11, need('--c-field-ink'))};`);
  lines.push(`--ink-line: ${K.under(31, need('--c-field-ink'), 0.8)};`);
  const [lineC, lineO] = rgba(need('--c-line'));
  lines.push(`--ink-under: ${K.under(23, lineC, lineO)};`);
  lines.push(`--ink-under-hover: ${K.under(23, need('--c-action-hover'), 1)};`);
  lines.push(`--ink-under-deep: ${K.under(23, need('--c-on-deep'), 0.45)};`);
  lines.push(`--ink-under-deep-hover: ${K.under(23, need('--c-deep-accent'), 1)};`);
  // choices and the select arrow: the field ink; chosen, the link red
  lines.push(`--mark-ring: ${K.ring(5, need('--c-field-ink'))};`);
  lines.push(`--mark-box: ${K.box(9, need('--c-field-ink'))};`);
  lines.push(`--mark-dot: ${K.blob(13, need('--c-action'))};`);
  lines.push(`--mark-tick: ${K.tick(need('--c-action'))};`);
  lines.push(`--mark-chevron: ${K.chevron(need('--c-field-ink'))};`);
  return '/* Generated by tools/fs-brushes.cjs from the colours in identity.css. Do not edit by hand. */\n:root {\n  ' + lines.join('\n  ') + '\n}\n';
}
module.exports = { draw, slots };
if (require.main === module) {
  const want = draw(fs.readFileSync(path.join(KIT, 'identity.css'), 'utf8')), file = path.join(KIT, 'brushes.css');
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== want) { console.error('kit/brushes.css is out of date: run node tools/fs-brushes.cjs'); process.exit(1); }
    console.log('brushes: ok');
  } else { fs.writeFileSync(file, want); console.log('wrote site-src/kit/brushes.css', want.length, 'bytes'); }
}
